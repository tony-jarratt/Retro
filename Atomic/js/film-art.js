function compileSprite(name, rows) {
  const h = rows.length, w = rows[0].length;
  rows.forEach((r, i) => {
    if (r.length !== w) throw new Error(`sprite ${name}: row ${i} is ${r.length} wide, not ${w}`);
    if (/[^#x.]/.test(r)) throw new Error(`sprite ${name}: row ${i} has a character other than # x .`);
  });
  const cell = (x, y) => (x < 0 || y < 0 || x >= w || y >= h ? '.' : rows[y][x]);
  const make = (flip) => {
    const c = document.createElement('canvas');
    c.width = w + 2; c.height = h + 2;
    const cx = c.getContext('2d');
    for (let y = -1; y <= h; y++) for (let x = -1; x <= w; x++) {
      const sx = flip ? w - 1 - x : x;
      let ch = cell(sx, y);
      if (ch === '.' && [[1, 0], [-1, 0], [0, 1], [0, -1]].some(([dx, dy]) => cell(sx + dx, y + dy) !== '.')) ch = 'x';
      if (ch === '.') continue;
      cx.fillStyle = ch === '#' ? '#fff' : '#000';
      cx.fillRect(x + 1, y + 1, 1, 1);
    }
    return c;
  };
  return { w: w + 2, h: h + 2, img: make(false), flip: make(true) };
}

